def _section(
    key: str, icon: str, order: int, *owners: str, audience: str = "everyone", topics: tuple[object, ...] = ()
) -> dict[str, object]:
    return {
        "key": key,
        "owner": "module:shell",
        "label_key": f"nav.section.{key}",
        "icon": icon,
        "order_hint": order,
        "audience": audience,
        "topics": topics,
        "default_for": tuple(f"module:{o}" for o in owners),
    }


