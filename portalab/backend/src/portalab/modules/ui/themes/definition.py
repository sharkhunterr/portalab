"""``ThemeDefinition`` validation and accessibility floor — the backend twin of the design system's
``themes/schema.ts`` and ``themes/floor.ts`` (spec 022 R2/R4, T008/T014/T027).

Themes are inert, closed documents: colors (``#hex``/``rgb()``), a mapping for each of the ten functional
states, optional typography/radii/motion/icons, backgrounds limited to bundled assets or raster data URIs
with a solid fallback, bundled sounds and notification defaults. Unknown keys are rejected. The floor then
checks WCAG 2.2 AA contrast on every declared pair and that critical states stay visible. The shared JSON
Schema (``theme.schema.json``, generated by the frontend) documents the same document.
"""

