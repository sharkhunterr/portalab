_HEX = re.compile(r"^#([0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$", re.I)
_RGB = re.compile(
    r"^rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*(?:,\s*(0|1|0?\.\d+))?\s*\)$", re.I
)

Color = Annotated[str, StringConstraints(max_length=64)]
Asset = Annotated[str, StringConstraints(pattern=r"^asset:[a-z0-9][a-z0-9._/-]{0,127}$")]
RasterUri = Annotated[
    str, StringConstraints(max_length=200_000, pattern=r"^data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/=]+$")
]


def is_color(value: str) -> bool:
    return bool(_HEX.match(value) or _RGB.match(value))


def parse_color(value: str) -> tuple[float, float, float, float]:
    hex_match = _HEX.match(value)
    if hex_match:
        digits = hex_match.group(1)
        if len(digits) <= 4:
            digits = "".join(c * 2 for c in digits)
        r, g, b = (int(digits[i : i + 2], 16) for i in (0, 2, 4))
        return r, g, b, (int(digits[6:8], 16) / 255 if len(digits) == 8 else 1.0)
    rgb_match = _RGB.match(value)
    if rgb_match:
        r, g, b = (min(255, int(rgb_match.group(i))) for i in (1, 2, 3))
        return r, g, b, float(rgb_match.group(4)) if rgb_match.group(4) is not None else 1.0
    raise ValueError(f"not a color: {value}")


def _over(top: tuple[float, ...], below: tuple[float, ...]) -> tuple[float, float, float, float]:
    a = top[3]
    return (
        top[0] * a + below[0] * (1 - a),
        top[1] * a + below[1] * (1 - a),
        top[2] * a + below[2] * (1 - a),
        1.0,
    )


def _luminance(color: tuple[float, ...]) -> float:
    def channel(value: float) -> float:
        c = value / 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    return 0.2126 * channel(color[0]) + 0.7152 * channel(color[1]) + 0.0722 * channel(color[2])


def contrast(foreground: str, background: str, base: str = "#ffffff") -> float:
    bg = _over(parse_color(background), parse_color(base))
    fg = _over(parse_color(foreground), bg)
    a, b = _luminance(fg), _luminance(bg)
    return (max(a, b) + 0.05) / (min(a, b) + 0.05)


class _Closed(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


def _check_color(value: str) -> str:
    if not is_color(value):
        raise ValueError("expected a #hex or rgb()/rgba() color")
    return value


class StateStyle(_Closed):
    fg: Color
    bg: Color
    icon: ICON_IDS | None = None
    label: Annotated[str, StringConstraints(pattern=r"^[a-z][a-zA-Z0-9_.-]{0,127}$")] | None = None
    opacity: Annotated[float, Field(ge=0, le=1)] | None = None
    display: Literal["inline", "block", "none"] | None = None

    _colors = field_validator("fg", "bg")(_check_color)


class Rarity(_Closed):
    common: Color
    rare: Color
    epic: Color
    legendary: Color

    _colors = field_validator("*")(_check_color)


class Colors(_Closed):
    surface: Color
    surfaceRaised: Color
    text: Color
    textMuted: Color
    border: Color
    accent: Color
    accentContrast: Color
    focus: Color
    accentAlt: Color | None = None
    rarity: Rarity | None = None

    _colors = field_validator(
        "surface", "surfaceRaised", "text", "textMuted", "border", "accent", "accentContrast", "focus"
    )(_check_color)

    @field_validator("accentAlt")
    @classmethod
    def _alt(cls, value: str | None) -> str | None:
        return None if value is None else _check_color(value)


