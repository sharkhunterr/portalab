"""Identifier generation (research R7, risk R-B).

All primary keys are UUIDv7 generated by the application. The third-party generator is wrapped here so the
rest of the code base depends on one function only (Python 3.14 adds ``uuid.uuid7`` to the stdlib).
"""

from uuid import UUID

import uuid6


def new_id() -> UUID:
    """Return a new time-ordered UUIDv7 as a plain :class:`uuid.UUID`."""
    return UUID(int=uuid6.uuid7().int)
