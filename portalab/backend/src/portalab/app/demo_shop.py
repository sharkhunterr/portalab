from typing import Any

Product = dict[str, Any]

SHOP: list[Product] = []


def _p(
    key: str,
    kind: str,
    price: int | None,
    rarity: str,
    en: str,
    fr: str,
    about_en: str,
    about_fr: str,
    payload: dict[str, Any],
    *,
    collection: str,
    icon: str | None = None,
    featured: bool = False,
    level: int | None = None,
    supply: int | None = None,
    limit: tuple[int, int] | None = None,
    repeatable: bool = False,
) -> None:
    SHOP.append(
        {
            "key": key,
            "type": kind,
            "price": price,
            "rarity": rarity,
            "names": {"en": en, "fr": fr},
            "descriptions": {"en": about_en, "fr": about_fr},
            "payload": payload,
            "collection": collection,
            "icon": icon,
            "featured": featured,
            "level": level,
            "supply": supply,
            "limit": limit,
            "repeatable": repeatable,
        }
    )


